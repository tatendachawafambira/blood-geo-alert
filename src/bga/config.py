"""Application configuration, read from .env by pydantic-settings.

Key material (field_key_b64, blind_pepper_b64) is read here and nowhere else.
Both are declared repr=False so that printing or logging the settings object
cannot leak them - see ADR-012 and NFR-SEC-04.
"""

from __future__ import annotations

from pydantic import AliasChoices, Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=False,
        extra="ignore",
    )

    # --- Database roles -------------------------------------------------
    # Three distinct roles, three distinct URLs. bga_owner runs migrations and
    # owns the tables; bga_app is the runtime role (no BYPASSRLS, not owner);
    # bga_audit is the write-only audit role. ADR-017.
    database_url_owner: str
    database_url_app: str
    database_url_audit: str

    # --- Key material ---------------------------------------------------
    # Aliases accept the BGA_FIELD_KEY / BGA_BLIND_PEPPER names generated by
    # the pre-flight step, so no key ever has to be re-typed or re-generated.
    field_key_b64: str = Field(
        repr=False,
        validation_alias=AliasChoices("field_key_b64", "bga_field_key"),
    )
    blind_pepper_b64: str = Field(
        repr=False,
        validation_alias=AliasChoices("blind_pepper_b64", "bga_blind_pepper"),
    )

    # --- Domain configuration -------------------------------------------
    radius_bands: list[int] = [3000, 5000, 10000]
    frequency_cap_days: int = 14
    dispatch_cap_multiplier: int = 10
    token_ttl_minutes: int = 120
    donor_base_url: str = "http://127.0.0.1:8001"
    quiet_hours_start: int = 21
    quiet_hours_end: int = 7

    @field_validator("database_url_owner", "database_url_app", "database_url_audit")
    @classmethod
    def _require_psycopg_driver(cls, v: str) -> str:
        # A bare postgresql:// URL makes SQLAlchemy 2.x reach for psycopg2,
        # which is not installed. The stack is psycopg 3; state it explicitly.
        if v.startswith("postgresql://"):
            return v.replace("postgresql://", "postgresql+psycopg://", 1)
        return v

    @field_validator("radius_bands")
    @classmethod
    def _bands_must_ascend(cls, v: list[int]) -> list[int]:
        # Matching walks the bands in order and stops at the first that fills
        # the requirement. Out-of-order bands would silently mis-escalate.
        if not v or sorted(set(v)) != v:
            raise ValueError("radius_bands must be non-empty and strictly ascending")
        return v


settings = Settings()
