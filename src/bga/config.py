"""Application configuration, read from .env by pydantic-settings.

Key material (field_key_b64, blind_pepper_b64) is read here and nowhere else.
Both are declared repr=False so that printing or logging the settings object
cannot leak them - see ADR-012 and NFR-SEC-04.
"""

from __future__ import annotations

from pydantic import AliasChoices, Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=False,
        extra="ignore",
    )

    # --- Database roles -------------------------------------------------
    # Three distinct roles, three distinct URLs. bga_owner runs migrations and
    # owns the tables; bga_app is the runtime role (no BYPASSRLS, not owner);
    # bga_audit is the write-only audit role. ADR-017.
    database_url_owner: str
    database_url_app: str
    database_url_audit: str

    # The donor response application (ADR-016). A deliberately narrow role: no
    # grant at all on core.donor or core.outbox, and only (id,
    # collection_point_id) on core.deficit_request. Empty means the donor app
    # refuses to start rather than quietly falling back to the wider app role.
    database_url_donor: str = ""

    # --- Key material ---------------------------------------------------
    # Aliases accept the BGA_FIELD_KEY / BGA_BLIND_PEPPER names generated by
    # the pre-flight step, so no key ever has to be re-typed or re-generated.
    field_key_b64: str = Field(
        repr=False,
        validation_alias=AliasChoices("field_key_b64", "bga_field_key"),
    )
    blind_pepper_b64: str = Field(
        repr=False,
        validation_alias=AliasChoices("blind_pepper_b64", "bga_blind_pepper"),
    )

    # --- Gateways -------------------------------------------------------
    # Names resolved by adapters.base.get_adapter. Not validated against the
    # registry here: config must not import adapters, which import config.
    # get_adapter raises on an unknown name rather than falling back.
    primary_gateway: str = "mock"
    secondary_gateway: str = "mock"

    # Seeds the runtime value in adapters/mock_sms.py, which the gateway
    # console then sets live to demonstrate retry, failover and the dead
    # letter queue. Bounded, because a rate outside 0..1 is a typo that would
    # otherwise mean either "never fail" or "always fail" silently.
    mock_failure_rate: float = Field(default=0.0, ge=0.0, le=1.0)

    # The only numbers a DEMONSTRATION gateway may actually message. Comma
    # separated E.164. Empty blocks every real send, which is deliberate: the
    # seeded register holds structurally valid Zimbabwean numbers belonging to
    # real people, and a forgotten setting must not message them. Ignored by
    # the mock (which sends nothing) and by africastalking (whose register will
    # hold consented donors). See adapters/allowlist.py.
    sms_allowlist: str = ""

    # Twilio, for a demonstration that delivers a real SMS. Optional: absent
    # values are caught by the adapter with an actionable message rather than
    # by a validation error at import, so the system still starts on the mock.
    # repr=False keeps the token out of every settings repr and traceback.
    twilio_account_sid: str = ""
    twilio_auth_token: str = Field(default="", repr=False)
    twilio_from_number: str = ""
    # Only set this when a public HTTPS callback exists. Without one, delivery
    # receipts never arrive and alerts settle at SENT - which FR-MSG-06 reports
    # as unconfirmed, never as failed.
    twilio_status_callback: str = ""

    # An Android handset running an SMS gateway app on the local network.
    android_sms_url: str = ""
    android_sms_username: str = ""
    android_sms_password: str = Field(default="", repr=False)
    android_sms_webhook_secret: str = Field(default="", repr=False)

    # --- Dispatch worker -------------------------------------------------
    dispatch_batch_size: int = Field(default=20, ge=1)
    worker_poll_seconds: float = Field(default=2.0, gt=0)

    # A row LOCKED for longer than this is assumed to belong to a worker that
    # died and is returned to the queue. Must comfortably exceed the time one
    # batch takes to submit, or two workers will process the same row.
    worker_lock_timeout_seconds: float = Field(default=300.0, gt=0)

    # Retry ladder. delay = uniform(0, min(cap, base * 2 ** attempts)) - full
    # jitter, so a provider coming back up is not hit by every worker at once.
    max_attempts: int = Field(default=5, ge=1)
    retry_base_seconds: float = Field(default=2.0, gt=0)
    retry_cap_seconds: float = Field(default=300.0, gt=0)

    # Circuit breaker. The success threshold is what gives it hysteresis: a
    # degraded provider that answers one request in three cannot flap the
    # breaker open and closed, which would split dispatch across two providers
    # and make delivery statistics uninterpretable.
    breaker_failure_threshold: int = Field(default=5, ge=1)
    breaker_cooldown_seconds: float = Field(default=30.0, gt=0)
    breaker_success_threshold: int = Field(default=3, ge=1)

    # --- Escalation scheduler --------------------------------------------
    # Deliberately short for a pilot and a demonstration. Real windows are an
    # operational decision for NBSZ, and FR-ADM-05 requires them to be
    # configurable without a deployment.
    scheduler_tick_seconds: float = Field(default=30.0, gt=0)
    no_response_window_minutes: int = Field(default=10, ge=1)
    facility_notify_minutes: int = Field(default=20, ge=1)
    max_request_lifetime_minutes: int = Field(default=120, ge=1)

    # --- Domain configuration -------------------------------------------
    radius_bands: list[int] = [3000, 5000, 10000]
    frequency_cap_days: int = 14
    dispatch_cap_multiplier: int = 10
    token_ttl_minutes: int = 120
    donor_base_url: str = "http://127.0.0.1:8001"
    quiet_hours_start: int = 21
    quiet_hours_end: int = 7

    @field_validator("database_url_owner", "database_url_app", "database_url_audit")
    @classmethod
    def _require_psycopg_driver(cls, v: str) -> str:
        # A bare postgresql:// URL makes SQLAlchemy 2.x reach for psycopg2,
        # which is not installed. The stack is psycopg 3; state it explicitly.
        if v.startswith("postgresql://"):
            return v.replace("postgresql://", "postgresql+psycopg://", 1)
        return v

    @field_validator("radius_bands")
    @classmethod
    def _bands_must_ascend(cls, v: list[int]) -> list[int]:
        # Matching walks the bands in order and stops at the first that fills
        # the requirement. Out-of-order bands would silently mis-escalate.
        if not v or sorted(set(v)) != v:
            raise ValueError("radius_bands must be non-empty and strictly ascending")
        return v


settings = Settings()
